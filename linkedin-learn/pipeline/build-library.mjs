/* build-library.mjs
   Writes site/data/library.js (window.LIBRARY = ...) and site/data/library.json.

   - If cache/enriched.json exists, builds the library from your saved items.
   - Otherwise it mirrors the existing library.js into library.json (so the JSON
     stays in sync with the hand-authored starter) and leaves the site as-is.
   Run: node pipeline/build-library.mjs
*/
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TOPICS, buildPaths } from "./lib/taxonomy.mjs";
import { loadLibraryFromJs, LIBRARY_JS, LIBRARY_JSON } from "./lib/load-library.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(__dirname, "cache");

function writeLibrary(lib) {
  const json = JSON.stringify(lib, null, 2);
  const js = "/* Generated by pipeline/build-library.mjs. Do not edit by hand. */\nwindow.LIBRARY = " + json + ";\n";
  fs.writeFileSync(LIBRARY_JS, js);
  fs.writeFileSync(LIBRARY_JSON, json);
}

const enrichedPath = path.join(CACHE, "enriched.json");
if (fs.existsSync(enrichedPath)) {
  const articles = JSON.parse(fs.readFileSync(enrichedPath, "utf8"));
  const topics = TOPICS.map(({ id, label, color, blurb }) => ({ id, label, color, blurb }));
  const lib = {
    meta: { generatedAt: new Date().toISOString().slice(0, 10), source: "linkedin", owner: process.env.OWNER || "", count: articles.length,
            note: "Built from your LinkedIn saved items." },
    topics, paths: buildPaths(articles), articles
  };
  writeLibrary(lib);
  console.log(`Built library from ${articles.length} saved article(s) -> site/data/library.js + library.json`);
} else {
  const lib = loadLibraryFromJs();
  fs.writeFileSync(LIBRARY_JSON, JSON.stringify(lib, null, 2));
  console.log(`No cache/enriched.json yet — mirrored the starter library.js into library.json (${lib.articles.length} articles). Run the ingest + fetch + enrich steps on your export to replace it.`);
}
